const WAM = "WAM 2026 membership directory";
const WIKI_COORDS = "Wikipedia primary coordinates, retrieved 2026-10-09";

function domainSite(host) {
  return site(`https://${host}/`, "directory-domain", `${WAM} email domain. Homepage was not opened. A candidate contact site, not a confirmed agenda publisher.`);
}

function place(row) {
  return {
    id: row.id,
    name: row.name,
    kind: row.kind,
    countyId: row.countyId,
    alsoCountyIds: row.alsoCountyIds ?? [],
    major: row.major ?? row.kind === "city",
    population: row.population ?? null,
    populationSource: row.population == null ? null : WAM,
    phone: row.phone ?? null,
    address: row.address,
    latitude: row.latitude,
    longitude: row.longitude,
    coordinateSource: WIKI_COORDS,
    website: row.website ?? null,
    architectureId: row.architectureId ?? "unobserved",
    tacticStatus: row.tacticStatus ?? (row.architectureId && row.architectureId !== "unobserved" ? "specified" : "fail-closed"),
    posting: row.posting ?? null,
    entities: row.entities ?? [],
    note: row.note ?? null,
    wamListed: row.wamListed !== false,
  };
}

const entity = (name, role, source, note) => ({ name, role, source, ...(note ? { note } : {}) });

